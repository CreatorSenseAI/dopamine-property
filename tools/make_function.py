"""Packs public/index.html into a single-file Railway Function (Bun) at
dist/railway-function.ts, so the game can be deployed without a Git repo.
Run: python3 tools/make_function.py
"""
import base64, gzip, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
html = (ROOT / "public/index.html").read_bytes()
gz = gzip.compress(html, compresslevel=9, mtime=0)
b64 = base64.b64encode(gz).decode()

code = f"""// Dopamine Property: generated by tools/make_function.py from public/index.html. Do not edit by hand.
const GZ = Buffer.from("{b64}", "base64");
const HTML = Bun.gunzipSync(GZ);
const head = {{
  "cache-control": "no-cache",
  "x-content-type-options": "nosniff",
  "referrer-policy": "strict-origin-when-cross-origin",
  vary: "accept-encoding",
}};

Bun.serve({{
  port: Number(Bun.env.PORT) || 3000,
  fetch(req) {{
    const url = new URL(req.url);
    if (url.pathname === "/healthz") return new Response("ok");
    const gzip = /\\bgzip\\b/.test(req.headers.get("accept-encoding") || "");
    return new Response(gzip ? GZ : HTML, {{
      headers: {{ ...head, "content-type": "text/html; charset=utf-8", ...(gzip ? {{ "content-encoding": "gzip" }} : {{}}) }},
    }});
  }},
}});
console.log("Dopamine Property is live");
"""
(ROOT / "dist").mkdir(exist_ok=True)
(ROOT / "dist/railway-function.ts").write_text(code)
print(f"dist/railway-function.ts: {len(code):,} chars (html {len(html):,} -> gz {len(gz):,})")
